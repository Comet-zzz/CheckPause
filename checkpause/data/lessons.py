def _move(
    fen,
    text_key,
    goal,
    target=None,
    accept=(),
    reply=None,
    hint=None,
    marks=(),
    arrows=(),
    text_params=None,
    note_key=None,
    note_params=None,
    success_key="learn_success",
):
    return LessonStep(
        kind=MOVE,
        fen=fen,
        text_key=text_key,
        text_params=dict(text_params or {}),
        note_key=note_key,
        note_params=dict(note_params or {}),
        goal=goal,
        target=target,
        accept=tuple(accept),
        reply=reply,
        hint=hint,
        marks=tuple(marks),
        arrows=tuple(arrows),
        success_key=success_key,
    )


